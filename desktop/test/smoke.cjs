// Run with Electron under a display (xvfb-run on Linux). No live account or network.
const { app, BrowserWindow, session } = require('electron')
const assert = require('node:assert/strict')
const { once } = require('node:events')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'mgt-smoke-')))
const timer = setTimeout(() => { console.error('Desktop smoke test timed out'); app.exit(1) }, 30000)

app.whenReady().then(async () => {
  const ses = session.fromPartition('persist:mgt')
  ses.protocol.handle('https', () => new Response('<!doctype html><title>MGT fixture</title><h1>Workspace</h1><a id="next" href="/inventory">Inventory</a><a id="blocked" href="file:///etc/passwd">Blocked file</a>', {headers:{'content-type':'text/html'}}))
  const [, win] = await once(app, 'browser-window-created')
  const contents = win.webContents
  await once(contents, 'did-finish-load')
  const preferences = contents.getLastWebPreferences()
  assert.equal(preferences.nodeIntegration, false)
  assert.equal(preferences.contextIsolation, true)
  assert.equal(preferences.sandbox, true)
  assert.equal(await contents.executeJavaScript('typeof require'), 'undefined')
  assert.equal(await contents.executeJavaScript('typeof process'), 'undefined')
  let next = once(contents, 'did-finish-load')
  await contents.executeJavaScript('document.querySelector("#next").click()')
  await next
  assert.equal(contents.getURL(), 'https://mgt-lake.vercel.app/inventory')
  await contents.executeJavaScript('document.querySelector("#blocked").click()')
  await new Promise(resolve => setTimeout(resolve, 100))
  assert.equal(contents.getURL(), 'https://mgt-lake.vercel.app/inventory')
  await contents.executeJavaScript('window.open("file:///etc/passwd")')
  assert.equal(BrowserWindow.getAllWindows().length, 1)
  ses.protocol.unhandle('https')
  ses.protocol.handle('https', () => Response.error())
  const recovery = new Promise(resolve => contents.on('did-finish-load', () => {
    if (contents.getURL().endsWith('/offline.html')) resolve()
  }))
  contents.loadURL('https://mgt-lake.vercel.app').catch(() => {})
  await recovery
  assert.match(await contents.executeJavaScript('document.body.innerText'), /Check your internet connection/)
  ses.protocol.unhandle('https')
  ses.protocol.handle('https', () => new Response('<h1>Connected</h1>', {headers:{'content-type':'text/html'}}))
  next = once(contents, 'did-finish-load')
  await contents.executeJavaScript('document.querySelector("a").click()')
  await next
  assert.equal(contents.getURL(), 'https://mgt-lake.vercel.app/')
  console.log('PASS: desktop launch, sandbox, navigation, blocked local files/popups, offline recovery and retry')
  clearTimeout(timer)
  app.exit(0)
}).catch(error => { console.error(error); clearTimeout(timer); app.exit(1) })
require('../main.cjs')
